#!/usr/bin/env python3
"""A builder tree (SYSROOT) for the offline tests of scripts/builder/20-fetch-verify.sh and
30-overlay.sh only.

    fixture_builder_sysroot.py <sample-dir> <sysroot> <files-dir> <repo-dir> [<inputs-case>]

<sysroot>/opt/cilium-bottlerocket/overlay holds copies of the sample's packages/, variant/ and
packer/, as the stage upload puts them on the builder, and <sysroot>/work is the empty work
volume (scripts/builder/lib.sh). In the copies, never in the tracked files:

  * packages/sources.lock is the lock of scripts/testlib/fixture_inputs.py for <inputs-case>
    (default good): file:// inputs in <files-dir>, signed with a test key whose public half is
    beside the lock. Its bottlerocket-source block is the sample's own block (the real lock's
    shape) with source=file://<repo-dir> and the commit and tag object of <repo-dir>;
  * variant/packages/nitro-sandbox/Cargo.toml names the fixture files and their SHA-512 values,
    so register-variant.py compares the package with this lock (E_PACKAGE_FILES).

<repo-dir>, when it does not exist yet, is made by scripts/testlib/fixture_br_clone.py, plus a
second commit with Makefile.toml (the Twoliter lines that packer/tools.lock pins, as the
upstream file sets them) and a root Cargo.lock, and the annotated tag v1.70.0 moved to that
commit. An existing <repo-dir> is used as it is. It prints the pinned commit and tag object.

Never point a real run at this tree: the files it pins are not the sample's inputs.
"""
import hashlib
import os
import re
import shutil
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fixture_br_clone  # noqa: E402
import fixture_inputs  # noqa: E402

TAG = "v1.70.0"
PACKAGE_IDS = ("runtime-release", "firecracker-release", "guest-image-eif", "guest-image-disk")


def blocks(text):
    """The key=value blocks of a lock, by id (continuation lines are left out)."""
    out = {}
    for block in text.split("\n\n"):
        kv = dict(ln.split("=", 1) for ln in block.splitlines() if re.match(r"^[a-z_0-9]+=", ln))
        if "id" in kv:
            out[kv["id"]] = kv
    return out


def tools_lock(sample, key):
    text = open(os.path.join(sample, "packer", "tools.lock")).read()
    found = re.findall(rf"^{key}=(.*)$", text, re.M)
    if len(found) != 1:
        raise SystemExit(f"tools.lock must set {key} once")
    return found[0]


def cargo_lock():
    """A stock-shaped root Cargo.lock: two path crates and one registry crate."""
    checksum = hashlib.sha256(b"fixture serde crate").hexdigest()
    return ("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n"
            '[[package]]\nname = "aws-k8s-1_36"\nversion = "0.1.0"\ndependencies = [\n "settings-plugins",\n]\n\n'
            '[[package]]\nname = "serde"\nversion = "1.0.228"\n'
            'source = "registry+https://github.com/rust-lang/crates.io-index"\n'
            f'checksum = "{checksum}"\n\n'
            '[[package]]\nname = "settings-plugins"\nversion = "0.1.0"\ndependencies = [\n "serde",\n]\n')


def make_repo(sample, repo):
    lock_tmp = repo + ".br-clone.lock"
    fixture_br_clone.main(sample, repo, lock_tmp)
    os.remove(lock_tmp)
    other = hashlib.sha256(b"fixture twoliter aarch64").hexdigest()
    with open(os.path.join(repo, "Makefile.toml"), "w") as f:
        f.write("[config]\nskip_core_tasks = true\n\n[env]\n"
                f'TWOLITER_VERSION = "{tools_lock(sample, "TWOLITER_VERSION")}"\n'
                f'TWOLITER_SHA256_AARCH64 = "{other}"\n'
                f'TWOLITER_SHA256_X86_64 = "{tools_lock(sample, "TWOLITER_SHA256_X86_64")}"\n')
    with open(os.path.join(repo, "Cargo.lock"), "w") as f:
        f.write(cargo_lock())
    fixture_br_clone.git(repo, "add", "Makefile.toml", "Cargo.lock")
    fixture_br_clone.git(repo, "commit", "-q", "-m", "stand-in v1.70.0 build files")
    fixture_br_clone.git(repo, "tag", "-f", "-a", TAG, "-m", "stand-in v1.70.0")


def main(sample, sysroot, files, repo, case="good"):
    sample, sysroot, files, repo = (os.path.abspath(p) for p in (sample, sysroot, files, repo))
    if not os.path.exists(repo):
        make_repo(sample, repo)
    commit = fixture_br_clone.git(repo, "rev-parse", "HEAD")
    tag_object = fixture_br_clone.git(repo, "rev-parse", f"refs/tags/{TAG}")

    overlay = os.path.join(sysroot, "opt", "cilium-bottlerocket", "overlay")
    os.makedirs(overlay)
    for d in ("packages", "variant", "packer"):
        shutil.copytree(os.path.join(sample, d), os.path.join(overlay, d), symlinks=True,
                        ignore=shutil.ignore_patterns("__pycache__"))
    os.makedirs(os.path.join(sysroot, "work"))

    lock = os.path.join(overlay, "packages", "sources.lock")
    real_text = open(os.path.join(sample, "packages", "sources.lock")).read()
    real = blocks(real_text)
    fixture_inputs.main(files, lock, case)
    parts = open(lock).read().split("\n\n")
    src = [p for p in real_text.split("\n\n") if p.startswith("id=bottlerocket-source\n")]
    if len(src) != 1:
        raise SystemExit("the sample lock must have one bottlerocket-source block")
    block = src[0]
    for key, value in (("source", "file://" + repo), ("commit", commit), ("tag_object", tag_object)):
        block, n = re.subn(rf"(?m)^{key}=.*$", f"{key}={value}", block)
        if n != 1:
            raise SystemExit(f"the bottlerocket-source block must have one {key}=")
    idx = [i for i, p in enumerate(parts) if p.startswith("id=bottlerocket-source\n")]
    if len(idx) != 1:
        raise SystemExit("the fixture lock must have one bottlerocket-source block")
    parts[idx[0]] = block
    with open(lock, "w") as f:
        f.write("\n\n".join(parts))

    fixture = blocks(open(lock).read())
    cargo = os.path.join(overlay, "variant", "packages", "nitro-sandbox", "Cargo.toml")
    text = open(cargo).read()
    for i in PACKAGE_IDS:
        for key in ("path", "sha512"):
            lock_key = "file" if key == "path" else "sha512"
            old, new = f'{key} = "{real[i][lock_key]}"', f'{key} = "{fixture[i][lock_key]}"'
            if text.count(old) != 1:
                raise SystemExit(f"{cargo}: expected one {key} line for {i}")
            text = text.replace(old, new)
    with open(cargo, "w") as f:
        f.write(text)
    print(f"commit={commit}")
    print(f"tag_object={tag_object}")


if __name__ == "__main__":
    main(*sys.argv[1:6])
